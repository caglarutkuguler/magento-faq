declare(strict_types=1);

namespace Megventure\Faq\Observer;

use Magento\Framework\Event\Observer;
use Magento\Framework\Event\ObserverInterface;
use Magento\Store\Model\StoreManagerInterface;
use Magento\UrlRewrite\Model\UrlPersistInterface;
use Magento\UrlRewrite\Service\V1\Data\UrlRewriteFactory;

/**
 * Gives a store view created after installation the /faq address.
 *
 * The address is written per store view when the module is installed, so a
 * store view added later (a second storefront on another theme, for instance)
 * would answer 404 on /faq until the data patch was run again.
 */
class PublishPageRewriteForNewStore implements ObserverInterface
{
    private const REQUEST_PATH = 'faq';
    private const TARGET_PATH = 'megventure_faq/index/index';
    private const ENTITY_TYPE = 'megventure-faq';

    /**
     * @param StoreManagerInterface $storeManager
     * @param UrlPersistInterface $urlPersist
     * @param UrlRewriteFactory $urlRewriteFactory
     */
    public function __construct(
        private readonly StoreManagerInterface $storeManager,
        private readonly UrlPersistInterface $urlPersist,
        private readonly UrlRewriteFactory $urlRewriteFactory
    ) {
    }

    /**
     * Publish the /faq address for every store view that lacks it.
     *
     * @param Observer $observer
     * @return void
     */
    public function execute(Observer $observer): void
    {
        $this->storeManager->reinitStores();

        foreach ($this->storeManager->getStores() as $store) {
            $rewrite = $this->urlRewriteFactory->create();
            $rewrite->setEntityType(self::ENTITY_TYPE)
                ->setEntityId(0)
                ->setRequestPath(self::REQUEST_PATH)
                ->setTargetPath(self::TARGET_PATH)
                ->setRedirectType(0)
                ->setStoreId((int) $store->getId())
                ->setIsAutogenerated(0)
                ->setDescription('Product FAQ: /faq page');

            try {
                $this->urlPersist->replace([$rewrite]);
            } catch (\Exception $e) {
                // A store view whose /faq belongs to a CMS page keeps it.
                continue;
            }
        }
    }
}
